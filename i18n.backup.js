  const originals = new WeakMap();

  function clean(text) {
    return text.replace(/\s+/g, " ").trim();
  }

  function applyLanguage(lang) {
    const dict = translations[lang] || {};

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.body.classList.toggle("rtl-language", lang === "ar");

    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT
    );

    let node;

    while ((node = walker.nextNode())) {
      const parent = node.parentElement;
      if (!parent) continue;

      if (["SCRIPT", "STYLE", "OPTION", "NOSCRIPT"].includes(parent.tagName)) {
        continue;
      }

      if (!originals.has(node)) {
        originals.set(node, node.nodeValue);
      }

      const original = originals.get(node);
      const key = clean(original);

      if (!key) continue;

      if (dict[key]) {
        const leading = original.match(/^\s*/)?.[0] || "";
        const trailing = original.match(/\s*$/)?.[0] || "";
        node.nodeValue = leading + dict[key] + trailing;
      } else {
        node.nodeValue = original;
      }
    }

    const select = document.getElementById("languageSelect");
    if (select) select.value = lang;

    localStorage.setItem("amiiraLanguage", lang);
  }

  document.addEventListener("DOMContentLoaded", () => {
    const select = document.getElementById("languageSelect");

    if (select) {
      select.innerHTML = `
        <option value="en">🇬🇧 English</option>
        <option value="so">🇸🇴 Soomaali</option>
        <option value="ar">🇸🇦 العربية</option>
        <option value="tr">🇹🇷 Türkçe</option>
      `;

      select.addEventListener("change", event => {
        applyLanguage(event.target.value);
      });
    }

    applyLanguage(localStorage.getItem("amiiraLanguage") || "en");
  });
